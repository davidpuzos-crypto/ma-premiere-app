/**
 * Espaces insécables à la française : jamais de « ? », de « : » ni de guillemet fermant
 * seul en début de ligne, jamais de « 10 » séparé de son « h ».
 */
export function typo(text) {
  return String(text || '')
    .replace(/« /g, '«\u00A0')
    .replace(/ »/g, '\u00A0»')
    .replace(/ ([?!:;])/g, '\u00A0$1')
    .replace(/(\d) (h|p\.|%|cm|signes)(?![A-Za-zÀ-ÿ])/g, '$1\u00A0$2')
    .replace(/n° /g, 'n°\u00A0');
}

/* Les émojis sont retirés à l'affichage : une note de bas de page reste sobre. */
export function plain(text) {
  return typo(String(text || '')
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}\u{200D}\u{23E9}-\u{23FF}\u{2300}-\u{231F}]/gu, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([.…])/g, '$1') // « café ☕. » devient « café. » (l'espace avant « ! » et « ? » est conservée)
    .trim());
}

function hash(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

const FOOTNOTES = () => QUOTES.concat(DICTIONARY);

/** La note de bas de page du jour : la même pour tout le monde, à commenter ensemble. */
export function footnoteOfDay(dayKey) {
  const pool = FOOTNOTES();
  return plain(pool[hash('note-' + dayKey) % pool.length]);
}

export function randomFootnote(not) {
  const pool = FOOTNOTES();
  let t = not;
  for (let i = 0; i < 6 && t === not; i++) t = plain(pool[Math.floor(Math.random() * pool.length)]);
  return t;
}

