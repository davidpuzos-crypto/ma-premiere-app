/** Semaine ISO : { year, week, id: 'AAAA-Sww' } */
export function isoWeek(date = new Date()) {
  const d = new Date(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()));
  const day = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() + 4 - day);
  const year = d.getUTCFullYear();
  const week = Math.ceil(((d - Date.UTC(year, 0, 1)) / 86400000 + 1) / 7);
  return { year, week, id: `${year}-S${String(week).padStart(2, '0')}` };
}

/** Les neuf cases de la semaine (tirage identique pour tout le monde). */
export function bingoGrid(weekId) {
  const idx = BINGO.map((_, i) => i);
  let seed = hash('bingo-' + weekId) || 1;
  const rnd = () => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296; };
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return idx.slice(0, 9).map(i => typo(BINGO[i]));
}

const BINGO_LINES = [[0, 1, 2], [3, 4, 5], [6, 7, 8], [0, 3, 6], [1, 4, 7], [2, 5, 8], [0, 4, 8], [2, 4, 6]];

export function bingoScore(ticks) {
  const on = new Set(ticks);
  const lines = BINGO_LINES.filter(l => l.every(i => on.has(i))).length;
  const n = on.size;
  let text;
  if (n === 9) text = 'Grille complète. Semaine de doctorat parfaitement normale.';
  else if (lines > 0) text = `Bingo${lines > 1 ? ' (' + lines + ' lignes)' : ''}. Ce n'est pas forcément une bonne nouvelle.`;
  else if (n === 0) text = 'Aucune case. Soit la semaine commence, soit vous mentez.';
  else text = `${n} case${n > 1 ? 's' : ''} sur 9. La semaine n'est pas finie.`;
  return { n, lines, text };
}

