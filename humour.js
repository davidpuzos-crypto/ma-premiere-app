const WEEKDAYS = ['dimanche', 'lundi', 'mardi', 'mercredi', 'jeudi', 'vendredi', 'samedi'];

export function todayLine({ done, goal, restDay, idleDays, streak, hasDeadline, weekday }) {
  if (done > 0 && done >= goal) {
    return weekday % 2
      ? 'Objectif du jour atteint. Vous pouvez fermer Word la tête haute.'
      : 'Objectif du jour atteint. Le reste de la journée vous appartient (en théorie).';
  }
  if (restDay) return 'Jour de repos. La thèse aussi a droit à son week-end.';
  if (idleDays >= 14) return `Dernière page notée il y a ${idleDays} jours. On ne juge pas. On note, c'est tout.`;
  if (idleDays >= 4) return `Dernière page notée il y a ${idleDays} jours. Le document ne dit rien, mais il n'en pense pas moins.`;
  if (streak >= 5) return `${streak} jours d'affilée. Ce serait dommage de s'arrêter un ${WEEKDAYS[weekday]}.`;
  return hasDeadline ? 'Objectif calculé pour tenir votre dépôt.' : 'Objectif du jour.';
}

