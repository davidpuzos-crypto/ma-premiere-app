export function promoLead(count, pages) {
  if (count === 0) return 'La salle des doctorants est encore vide. Il faut bien que quelqu\'un allume la lumière.';
  const who = count === 1 ? '1 doctorant·e est inscrit·e' : `${count} doctorant·es sont inscrit·es`;
  if (pages <= 0) return typo(`${who} dans la promo. Aucune page notée cette semaine : tout le monde réfléchit très fort.`);
  const p = Math.round(pages * 10) / 10;
  const theses = pages / 250;
  const eq = pages >= 25
    ? ` Soit ${theses.toLocaleString('fr-FR', { maximumFractionDigits: 1 })} thèse, à peu près.`
    : ' C\'est un début, et les débuts comptent.';
  return `${who} dans la promo. Cette semaine, ${p.toLocaleString('fr-FR')} page${p >= 2 ? 's ont été noircies' : ' a été noircie'}.${eq}`;
}

